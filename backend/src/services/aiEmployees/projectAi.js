/**
 * Agent 2 — Software Project & Task Management AI
 * Specialization: Milestone tracking, WBS breakdown, overdue task detection, sprint health & blocker escalation
 */

const { PrismaClient } = require('@prisma/client');
const prisma = new PrismaClient();
const aiGateway = require('../aiGateway');

class ProjectAiService {
  constructor() {
    this.agentCode = 'project_ai';
  }

  /**
   * Automatically generate Work Breakdown Structure (WBS) for a newly onboarded project
   */
  async generateProjectWbs(projectId) {
    const project = await prisma.project.findUnique({
      where: { id: projectId },
      include: { client: true }
    });
    if (!project) throw new Error(`Project #${projectId} not found`);

    const systemPrompt = `You are the Lead Agile Project Manager AI for Kiaan Technology.
Given project requirements, generate a structured agile sprint breakdown in JSON:
{
  "projectCode": "string",
  "totalEstimatedHours": 160,
  "milestones": [
    {
      "title": "Milestone 1: Architectural Foundation & Wireframes",
      "dueDateOffsetDays": 14,
      "tasks": [
        { "title": "Database Schema Design & Prisma Migration", "taskType": "FEATURE", "estimatedHours": 16, "priority": "HIGH" },
        { "title": "API Authentication & RBAC Middleware", "taskType": "FEATURE", "estimatedHours": 12, "priority": "HIGH" },
        { "title": "Figma UX/UI Review with Client", "taskType": "DOCS", "estimatedHours": 8, "priority": "MEDIUM" }
      ]
    },
    {
      "title": "Milestone 2: Core Platform Development",
      "dueDateOffsetDays": 30,
      "tasks": [
        { "title": "Core Business Entity CRUD & Validations", "taskType": "FEATURE", "estimatedHours": 32, "priority": "HIGH" },
        { "title": "Third-party Webhook & Notification Integrations", "taskType": "INTEGRATION", "estimatedHours": 20, "priority": "MEDIUM" }
      ]
    },
    {
      "title": "Milestone 3: QA, Staging UAT & Production Launch",
      "dueDateOffsetDays": 45,
      "tasks": [
        { "title": "Automated Unit & End-to-End Test Suite", "taskType": "TEST", "estimatedHours": 16, "priority": "HIGH" },
        { "title": "Cloud Infrastructure Provisioning & CI/CD Pipeline", "taskType": "DEVOPS", "estimatedHours": 16, "priority": "HIGH" },
        { "title": "Production Deployment & Handover Signoff", "taskType": "HANDOVER", "estimatedHours": 8, "priority": "CRITICAL" }
      ]
    }
  ],
  "riskAssessment": "Low - standard modern web architecture with well-defined requirements."
}`;

    const userPrompt = `Project: ${project.title}. Type: ${project.projectType || 'Custom Web Application'}. Description: ${project.description || 'Enterprise IT Client Application'}. Client: ${project.client?.firstName || 'Client'} ${project.client?.lastName || ''}`;

    const result = await aiGateway.complete({
      agentCode: this.agentCode,
      systemPrompt,
      userPrompt,
      taskType: 'wbs_generation',
      triggerEvent: 'project:created',
      entityType: 'project',
      entityId: project.id,
      contextData: { projectId: project.id, projectTitle: project.title }
    });

    const parsed = result.data;

    // Seed generated milestones & tasks into database
    if (parsed.milestones && Array.isArray(parsed.milestones)) {
      for (let i = 0; i < parsed.milestones.length; i++) {
        const m = parsed.milestones[i];
        const dueDate = new Date(Date.now() + (m.dueDateOffsetDays || (i + 1) * 14) * 86400000);
        const milestone = await prisma.projectMilestone.create({
          data: {
            projectId: project.id,
            title: m.title,
            description: `Generated by Project Management AI for sprint phase ${i + 1}`,
            orderIndex: i + 1,
            dueDate,
            status: i === 0 ? 'IN_PROGRESS' : 'PENDING'
          }
        });

        if (m.tasks && Array.isArray(m.tasks)) {
          for (const t of m.tasks) {
            await prisma.projectTask.create({
              data: {
                projectId: project.id,
                milestoneId: milestone.id,
                title: t.title,
                taskType: t.taskType || 'FEATURE',
                priority: t.priority || 'MEDIUM',
                estimatedHours: t.estimatedHours || 8,
                status: 'TODO',
                dueDate
              }
            });
          }
        }
      }
    }

    return { projectId: project.id, wbs: parsed };
  }

  /**
   * Scan active projects for overdue tasks, blocked milestones, and delivery delays
   */
  async scanProjectDeadlines() {
    const now = new Date();
    const overdueTasks = await prisma.projectTask.findMany({
      where: {
        status: { in: ['TODO', 'IN_PROGRESS', 'REVIEW'] },
        dueDate: { lt: now }
      },
      include: { project: true },
      take: 20
    });

    const riskReport = [];
    for (const task of overdueTasks) {
      riskReport.push({
        taskId: task.id,
        taskTitle: task.title,
        projectName: task.project?.title || 'Unknown Project',
        projectId: task.projectId,
        priority: task.priority,
        dueDate: task.dueDate,
        delayDays: Math.ceil((now - new Date(task.dueDate)) / (1000 * 60 * 60 * 24))
      });
    }

    await aiGateway.logExecution({
      agentCode: this.agentCode,
      taskType: 'project_deadline_scan',
      triggerEvent: 'cron:15min',
      entityType: 'task_batch',
      entityId: 'deadline_scan',
      inputPayload: { totalOverdueFound: overdueTasks.length },
      outputResult: { overdueCount: overdueTasks.length, riskReport },
      executionTimeMs: 140,
      tokensUsed: 95,
      costEstimate: 0.0001,
      status: 'COMPLETED'
    });

    return {
      totalOverdue: overdueTasks.length,
      overdueTasks: riskReport,
      health: overdueTasks.length === 0 ? 'HEALTHY' : overdueTasks.length <= 3 ? 'WARNING' : 'CRITICAL'
    };
  }

  /**
   * Prepare Sprint Status Summary for Project Managers
   */
  async generateSprintSummary(projectId) {
    const project = await prisma.project.findUnique({
      where: { id: projectId },
      include: { milestones: true, tasks: true }
    });
    if (!project) throw new Error(`Project #${projectId} not found`);

    const totalTasks = project.tasks.length;
    const completedTasks = project.tasks.filter(t => t.status === 'DONE').length;
    const inProgressTasks = project.tasks.filter(t => t.status === 'IN_PROGRESS').length;
    const completionRate = totalTasks > 0 ? Math.round((completedTasks / totalTasks) * 100) : 0;

    return {
      projectId: project.id,
      title: project.title,
      totalMilestones: project.milestones.length,
      totalTasks,
      completedTasks,
      inProgressTasks,
      completionRate: `${completionRate}%`,
      status: project.status
    };
  }
}

module.exports = new ProjectAiService();
